// =============================================================================
// tb_snax_llm_layer_smoke.sv
//
// First-milestone system TB for snax_llm_top_clean:
//   * DMA MODEL  : a behavioural DMA master (master 0) with a DRAM array.  It
//                  executes a descriptor-style block copy  DRAM <-> TCDM
//                  (dram_addr, tcdm_addr, size, dir) by issuing 72b accesses on
//                  dma_mem_req_*.
//   * CPU MODEL  : a behavioural CPU (RV32I stand-in) that drives the CSR port
//                  (cpu_csr_*) and the TCDM port (cpu_mem_*), able to read/write
//                  words and, later, run elementwise kernels on TCDM.
//   * The flow reuses the proven GEMM stimulus/golden:
//       1. build DRAM image from tcdm_preload_{addr,data}
//       2. DMA block-copy DRAM -> TCDM (descriptor semantics)
//       3. CPU poke/peek a scratch TCDM word (master-1 sanity)
//       4. CPU programs the sequencer CSR and launches GEMM
//       5. DMA reads back bank-17 output words, bit-exact vs golden
//
// This proves the CPU/DMA plumbing around the accelerator.  Elementwise CPU
// kernels (RMSNorm/RoPE/SiLU) and full-layer orchestration are added later;
// stub task names are provided at the bottom.
//
// Data/golden files: sim_snax_llm_top_gemm/hex/...  (generated by
//   tb/generate_snax_llm_top_gemm_data.py)
// =============================================================================
