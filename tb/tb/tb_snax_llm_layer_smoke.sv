// =============================================================================
// tb_snax_llm_layer_smoke.sv
//
// First-milestone system TB for snax_llm_top_clean:
//   * DMA MODEL  : a behavioural DMA master (master 0) with a DRAM array.  It
//                  executes a descriptor-style block copy  DRAM <-> TCDM
//                  (dram_addr, tcdm_addr, size, dir) by issuing 72b accesses on
//                  dma_mem_req_*.
//   * CPU MODEL  : a behavioural CPU (RV32I stand-in) that drives the CSR port
//                  (cpu_csr_*) and the TCDM port (cpu_mem_*), able to read/write
//                  words and, later, run elementwise kernels on TCDM.
//   * The flow reuses the proven GEMM stimulus/golden:
//       1. build DRAM image from tcdm_preload_{addr,data}
//       2. DMA block-copy DRAM -> TCDM (descriptor semantics)
//       3. CPU poke/peek a scratch TCDM word (master-1 sanity)
//       4. CPU programs the sequencer CSR and launches GEMM
//       5. DMA reads back bank-17 output words, bit-exact vs golden
//
// This proves the CPU/DMA plumbing around the accelerator.  Elementwise CPU
// kernels (RMSNorm/RoPE/SiLU) and full-layer orchestration are added later;
// stub task names are provided at the bottom.
//
// Data/golden files: sim_snax_llm_top_gemm/hex/...  (generated by
//   tb/generate_snax_llm_top_gemm_data.py)
// =============================================================================
`timescale 1ns/1ps

module tb_snax_llm_layer_smoke;

    // -------------------------------------------------------------------------
    // Problem shape (must match the GEMM stimulus generator)
    // -------------------------------------------------------------------------
    localparam int M_TILES    = 2;
    localparam int N_TILES    = 2;
    localparam int K_BLOCKS   = 4;
    localparam int NUM_VEC    = N_TILES * M_TILES * 16;   // 64
    localparam int NUM_WORD   = NUM_VEC * 4;              // 256
    localparam int NUM_FP16   = NUM_WORD * 4;             // 1024
    localparam int NUM_PRELOAD= 256;
    localparam int CLK_PERIOD = 10;

    localparam int OUT_BANK   = 17;
    localparam logic [31:0] Q_BASE   = 32'h0000_0100;  // bank 16, word 0
    localparam logic [31:0] OUT_BASE = 32'h0000_0110;  // bank 17, word 0
    localparam logic [31:0] RING_BASE= 32'h0000_0000;  // bank 0,  word 0

    // TCDM image spans bank0..31, word0..127 covered by 4096 x 16-byte slots.
    localparam int TCDM_SLOTS = 4096;                       // 64 KiB address span
    localparam int TCDM_BYTES = TCDM_SLOTS * 16;

    // CSR register indices (snax_csr_manager)
    localparam logic [11:0] A_CTRL      = 12'd0;
    localparam logic [11:0] A_WO_BASE   = 12'd13;
    localparam logic [11:0] A_WO_NV     = 12'd14;
    localparam logic [11:0] A_WO_LS     = 12'd15;
    localparam logic [11:0] A_SEQ_CTRL  = 12'd31;
    localparam logic [11:0] A_GEMM_NT   = 12'd38;
    localparam logic [11:0] A_GEMM_MT   = 12'd39;
    localparam logic [11:0] A_GEMM_KB   = 12'd40;
    localparam logic [11:0] A_RING_BASE = 12'd41;
    localparam logic [11:0] A_Q_BASE    = 12'd42;
    localparam logic [11:0] A_OUT_BASE  = 12'd43;
    localparam logic [11:0] A_START     = 12'd47;
    localparam logic [11:0] A_RO_SEQ    = 12'd48;
    localparam logic [11:0] A_RO_ID     = 12'd55;
    localparam logic [31:0] CSR_ID_VALUE= 32'h534E_4146;

    // -------------------------------------------------------------------------
    // DUT signals
    // -------------------------------------------------------------------------
    logic clk, rst_n;

    logic        csr_req_valid, csr_req_ready, csr_req_write;
    logic [11:0] csr_req_addr;
    logic [31:0] csr_req_data;
    logic        csr_rsp_valid, csr_rsp_ready;
    logic [31:0] csr_rsp_data;

    logic        cpu_mem_req_valid, cpu_mem_req_ready;
    logic [31:0] cpu_mem_req_addr;
    logic        cpu_mem_req_write;
    logic [71:0] cpu_mem_req_wdata;
    logic [8:0]  cpu_mem_req_strb;
    logic        cpu_mem_rsp_valid;
    logic [71:0] cpu_mem_rsp_rdata;

    logic        dma_mem_req_valid, dma_mem_req_ready;
    logic [31:0] dma_mem_req_addr;
    logic        dma_mem_req_write;
    logic [71:0] dma_mem_req_wdata;
    logic [8:0]  dma_mem_req_strb;
    logic        dma_mem_rsp_valid;
    logic [71:0] dma_mem_rsp_rdata;

    logic        dma_desc_valid, dma_desc_ready;
    logic [1:0]  dma_desc_dir;
    logic [31:0] dma_desc_dram_addr, dma_desc_tcdm_addr, dma_desc_size;
    logic        dma_desc_done;

    logic        busy, done_irq;

    // -------------------------------------------------------------------------
    // Clock & reset
    // -------------------------------------------------------------------------
    initial begin
        clk = 1'b0;
        forever #(CLK_PERIOD/2) clk = ~clk;
    end

    initial begin
        rst_n = 1'b0;
        #(CLK_PERIOD * 5);
        rst_n = 1'b1;
    end

    // -------------------------------------------------------------------------
    // DUT
    // -------------------------------------------------------------------------
    snax_llm_top_clean dut (
        .clk                     (clk),
        .rst_n                   (rst_n),

        .cpu_csr_req_valid_i     (csr_req_valid),
        .cpu_csr_req_ready_o     (csr_req_ready),
        .cpu_csr_req_write_i     (csr_req_write),
        .cpu_csr_req_addr_i      (csr_req_addr),
        .cpu_csr_req_data_i      (csr_req_data),
        .cpu_csr_rsp_valid_o     (csr_rsp_valid),
        .cpu_csr_rsp_ready_i     (csr_rsp_ready),
        .cpu_csr_rsp_data_o      (csr_rsp_data),

        .cpu_mem_req_valid_i     (cpu_mem_req_valid),
        .cpu_mem_req_ready_o     (cpu_mem_req_ready),
        .cpu_mem_req_addr_i      (cpu_mem_req_addr),
        .cpu_mem_req_write_i     (cpu_mem_req_write),
        .cpu_mem_req_wdata_i     (cpu_mem_req_wdata),
        .cpu_mem_req_strb_i      (cpu_mem_req_strb),
        .cpu_mem_rsp_valid_o     (cpu_mem_rsp_valid),
        .cpu_mem_rsp_rdata_o     (cpu_mem_rsp_rdata),

        .dma_mem_req_valid_i     (dma_mem_req_valid),
        .dma_mem_req_ready_o     (dma_mem_req_ready),
        .dma_mem_req_addr_i      (dma_mem_req_addr),
        .dma_mem_req_write_i     (dma_mem_req_write),
        .dma_mem_req_wdata_i     (dma_mem_req_wdata),
        .dma_mem_req_strb_i      (dma_mem_req_strb),
        .dma_mem_rsp_valid_o     (dma_mem_rsp_valid),
        .dma_mem_rsp_rdata_o     (dma_mem_rsp_rdata),

        .dma_desc_valid_o        (dma_desc_valid),
        .dma_desc_ready_i        (dma_desc_ready),
        .dma_desc_dir_o          (dma_desc_dir),
        .dma_desc_dram_addr_o    (dma_desc_dram_addr),
        .dma_desc_tcdm_addr_o    (dma_desc_tcdm_addr),
        .dma_desc_size_o         (dma_desc_size),
        .dma_desc_done_i         (dma_desc_done),

        .subsystem_busy_o        (busy),
        .subsystem_done_irq_o    (done_irq)
    );

    // Optional waveform dump
    initial begin
        if (!$test$plusargs("NO_WAVE")) begin
`ifdef FST_TRACE
            $dumpfile("tb_snax_llm_layer_smoke.fst");
`else
            $dumpfile("tb_snax_llm_layer_smoke.vcd");
`endif
            if ($test$plusargs("WAVE_DEEP"))
                $dumpvars(0, tb_snax_llm_layer_smoke);
            else
                $dumpvars(0, dut);
        end
    end

    // -------------------------------------------------------------------------
    // DRAM MODEL (72b, indexed by TCDM 16-byte slot = addr>>4)
    // -------------------------------------------------------------------------
    logic [71:0] dram [0:TCDM_SLOTS-1];

    // -------------------------------------------------------------------------
    // Reference data
    // -------------------------------------------------------------------------
    logic [31:0] pre_addr [0:NUM_PRELOAD-1];
    logic [71:0] pre_data [0:NUM_PRELOAD-1];
    logic [71:0] exp_word [0:NUM_WORD-1];
    logic [71:0] out_words[0:NUM_WORD-1];

    int  checks_pass, checks_fail;
    int  fp16_match, fp16_mismatch;
    real max_abs_err;

    function automatic logic [31:0] tcdm_addr(input int word, input int bank);
        tcdm_addr = (32'(word) << 9) | (32'(bank) << 4);
    endfunction

    function automatic real fp16_to_real(input logic [15:0] hv);
        logic       s; logic [4:0] e; logic [9:0] mf; real v;
        s = hv[15]; e = hv[14:10]; mf = hv[9:0];
        if (e == 5'd0 && mf == 10'd0) return 0.0;
        if (e == 5'b11111) return s ? -999999.0 : 999999.0;
        if (e == 5'd0) v = real'(mf) / 16777216.0;
        else           v = (1.0 + real'(mf) / 1024.0) * $itor(32'd1 << e) / 32768.0;
        return s ? -v : v;
    endfunction

    task automatic check(input bit cond, input string name);
        if (cond) checks_pass = checks_pass + 1;
        else begin
            checks_fail = checks_fail + 1;
            $display("    [FAIL] %s", name);
        end
    endtask

    // =========================================================================
    // CPU MODEL  (CSR port + TCDM master 1)
    // =========================================================================
    task automatic cpu_csr_write(input logic [11:0] a, input logic [31:0] d);
        begin
            @(negedge clk);
            csr_req_valid = 1'b1; csr_req_write = 1'b1;
            csr_req_addr = a;     csr_req_data = d;
            #1;
            while (!csr_req_ready) begin @(negedge clk); #1; end
            @(posedge clk);
            @(negedge clk);
            csr_req_valid = 1'b0;
        end
    endtask

    task automatic cpu_csr_read(input logic [11:0] a, output logic [31:0] d);
        begin
            @(negedge clk);
            csr_req_valid = 1'b1; csr_req_write = 1'b0;
            csr_req_addr = a;     csr_req_data = 32'd0;
            #1;
            while (!csr_req_ready) begin @(negedge clk); #1; end
            @(posedge clk);
            @(negedge clk);
            csr_req_valid = 1'b0;
            d = csr_rsp_data;
        end
    endtask

    task automatic cpu_mem_write(input logic [31:0] a, input logic [71:0] d);
        begin
            @(negedge clk);
            cpu_mem_req_valid = 1'b1; cpu_mem_req_write = 1'b1;
            cpu_mem_req_addr = a; cpu_mem_req_wdata = d; cpu_mem_req_strb = 9'h1FF;
            #1;
            while (!cpu_mem_req_ready) begin @(negedge clk); #1; end
            @(posedge clk);
            @(negedge clk);
            cpu_mem_req_valid = 1'b0; cpu_mem_req_write = 1'b0; cpu_mem_req_strb = 9'h000;
        end
    endtask

    task automatic cpu_mem_read(input logic [31:0] a, output logic [71:0] d);
        begin
            @(negedge clk);
            cpu_mem_req_valid = 1'b1; cpu_mem_req_write = 1'b0;
            cpu_mem_req_addr = a; cpu_mem_req_wdata = '0; cpu_mem_req_strb = 9'h000;
            #1;
            while (!cpu_mem_req_ready) begin @(negedge clk); #1; end
            @(posedge clk);
            @(negedge clk);
            cpu_mem_req_valid = 1'b0;
            d = cpu_mem_rsp_rdata;
        end
    endtask

    // =========================================================================
    // DMA MODEL  (DRAM array + TCDM master 0)
    // =========================================================================
    task automatic dma_write(input logic [31:0] a, input logic [71:0] d);
        begin
            @(negedge clk);
            dma_mem_req_valid = 1'b1; dma_mem_req_write = 1'b1;
            dma_mem_req_addr = a; dma_mem_req_wdata = d; dma_mem_req_strb = 9'h1FF;
            #1;
            while (!dma_mem_req_ready) begin @(negedge clk); #1; end
            @(posedge clk);
            @(negedge clk);
            dma_mem_req_valid = 1'b0; dma_mem_req_write = 1'b0; dma_mem_req_strb = 9'h000;
        end
    endtask

    task automatic dma_read(input logic [31:0] a, output logic [71:0] d);
        begin
            @(negedge clk);
            dma_mem_req_valid = 1'b1; dma_mem_req_write = 1'b0;
            dma_mem_req_addr = a; dma_mem_req_wdata = '0; dma_mem_req_strb = 9'h000;
            #1;
            while (!dma_mem_req_ready) begin @(negedge clk); #1; end
            @(posedge clk);
            @(negedge clk);
            dma_mem_req_valid = 1'b0;
            d = dma_mem_rsp_rdata;
        end
    endtask

    // Descriptor-style block copy: 16-byte slots, dir 0 = DRAM->TCDM, 1 = reverse.
    // This is exactly the operation a dma_desc (dram_addr, tcdm_addr, size, dir)
    // asks the external DMA to perform.
    task automatic dma_block_copy(input logic [31:0] dram_byte,
                                  input logic [31:0] tcdm_byte,
                                  input int unsigned nslots,
                                  input logic dir);
        int unsigned i;
        logic [71:0] w;
        begin
            for (i = 0; i < nslots; i++) begin
                if (dir == 1'b0) begin
                    dma_write(tcdm_byte + (i << 4), dram[(dram_byte >> 4) + i]);
                end else begin
                    dma_read(tcdm_byte + (i << 4), w);
                    dram[(dram_byte >> 4) + i] = w;
                end
            end
        end
    endtask

    // =========================================================================
    // Main sequence
    // =========================================================================
    int i, cycle_cnt;
    logic [31:0] rd32;
    logic [71:0] peek;
    bit seen_done;
    localparam logic [71:0] POKE_VAL = 72'hCAFE_0000_0000_0000_5A;
    localparam logic [31:0] POKE_ADDR = 32'h0003_E940; // bank20, word500 (unused)

    initial begin
        csr_req_valid = 1'b0; csr_req_write = 1'b0; csr_req_addr = '0; csr_req_data = '0;
        csr_rsp_ready = 1'b1;
        cpu_mem_req_valid = 1'b0; cpu_mem_req_write = 1'b0; cpu_mem_req_addr = '0;
        cpu_mem_req_wdata = '0; cpu_mem_req_strb = '0;
        dma_mem_req_valid = 1'b0; dma_mem_req_write = 1'b0; dma_mem_req_addr = '0;
        dma_mem_req_wdata = '0; dma_mem_req_strb = '0;
        dma_desc_ready = 1'b1; dma_desc_done = 1'b0;

        checks_pass = 0; checks_fail = 0;
        fp16_match = 0; fp16_mismatch = 0; max_abs_err = 0.0;

        $readmemh("sim_snax_llm_top_gemm/hex/tcdm_preload_addr.hex", pre_addr);
        $readmemh("sim_snax_llm_top_gemm/hex/tcdm_preload_data.hex", pre_data);
        $readmemh("sim_snax_llm_top_gemm/hex/expected_out_words.hex", exp_word);

        wait (rst_n == 1'b1);
        repeat (10) @(posedge clk);

        $display("\n=======================================================");
        $display("  tb_snax_llm_layer_smoke: CPU + DMA + GEMM system smoke");
        $display("  M=%0d N=%0d K=%0d  (M_T=%0d N_T=%0d K_B=%0d)",
                 M_TILES*16, N_TILES*16, K_BLOCKS*16, M_TILES, N_TILES, K_BLOCKS);
        $display("=======================================================");

        // 1. Build DRAM image from the preload list (slot = tcdm_addr>>4)
        $display("[1] Building DRAM image (%0d slots) from preload list ...", TCDM_SLOTS);
        for (i = 0; i < TCDM_SLOTS; i++) dram[i] = 72'd0;
        for (i = 0; i < NUM_PRELOAD; i++) dram[pre_addr[i] >> 4] = pre_data[i];

        // 2. DMA block-copy DRAM -> TCDM (descriptor semantics)
        $display("[2] DMA block-copy DRAM -> TCDM (%0d slots = %0d bytes) ...",
                 TCDM_SLOTS, TCDM_BYTES);
        dma_block_copy(32'd0, 32'd0, TCDM_SLOTS, 1'b0);

        // 3. CPU master-1 sanity: poke/peek a scratch word
        $display("[3] CPU TCDM poke/peek @0x%08X ...", POKE_ADDR);
        cpu_mem_write(POKE_ADDR, POKE_VAL);
        cpu_mem_read(POKE_ADDR, peek);
        check(peek === POKE_VAL, "CPU TCDM read/write (master 1)");

        // 4. CPU programs the sequencer descriptor and launches GEMM
        $display("[4] CPU programs CSR and launches GEMM ...");
        cpu_csr_read(A_RO_ID, rd32);
        check(rd32 == CSR_ID_VALUE, "CSR hardware ID (SNAF)");

        cpu_csr_write(A_CTRL,      32'h0);        // sequencer owns control
        cpu_csr_write(A_SEQ_CTRL,  32'h0);        // op_mode=00 GEMM, DMA off
        cpu_csr_write(A_GEMM_NT,   N_TILES);
        cpu_csr_write(A_GEMM_MT,   M_TILES);
        cpu_csr_write(A_GEMM_KB,   K_BLOCKS);
        cpu_csr_write(A_RING_BASE, RING_BASE);
        cpu_csr_write(A_Q_BASE,    Q_BASE);
        cpu_csr_write(A_OUT_BASE,  OUT_BASE);
        cpu_csr_write(A_WO_BASE,   OUT_BASE);
        cpu_csr_write(A_WO_NV,     NUM_VEC);
        cpu_csr_write(A_WO_LS,     32'h200);
        cpu_csr_write(A_START,     32'h0000_0003);

        // 5. Wait for completion
        seen_done = 1'b0; cycle_cnt = 0;
        while (!seen_done && cycle_cnt < 20000) begin
            @(posedge clk);
            cycle_cnt = cycle_cnt + 1;
            if (done_irq && !busy) seen_done = 1'b1;
        end
        $display("    Completed in %0d cycles (busy=%0b done_irq=%0b)",
                 cycle_cnt, busy, done_irq);
        check(seen_done, "Sequencer finished without timeout");

        repeat (50) @(posedge clk);

        // 6. DMA reads back result words from bank 17, compare bit-exact
        $display("[6] DMA readback %0d words from bank %0d, checking ...",
                 NUM_WORD, OUT_BANK);
        for (i = 0; i < NUM_WORD; i++) dma_read(tcdm_addr(i, OUT_BANK), out_words[i]);

        for (i = 0; i < NUM_WORD; i++) begin
            for (int e = 0; e < 4; e++) begin
                logic [15:0] afp, efp;
                real ar, er, diff;
                afp = out_words[i][e*16 +: 16];
                efp = exp_word[i][e*16 +: 16];
                ar = fp16_to_real(afp); er = fp16_to_real(efp);
                diff = ar - er; if (diff < 0.0) diff = -diff;
                if (diff > max_abs_err) max_abs_err = diff;
                if (afp === efp) fp16_match = fp16_match + 1;
                else begin
                    fp16_mismatch = fp16_mismatch + 1;
                    if (fp16_mismatch <= 10)
                        $display("    Mismatch word=%0d elem=%0d: act=0x%04X exp=0x%04X",
                                 i, e, afp, efp);
                end
            end
        end

        $display("\n=======================================================");
        $display("  SYSTEM SMOKE RESULTS");
        $display("=======================================================");
        $display("  FP16 Matches       : %0d / %0d", fp16_match, NUM_FP16);
        $display("  FP16 Mismatches    : %0d", fp16_mismatch);
        $display("  Max Absolute Error : %f", max_abs_err);
        $display("  GEMM Cycles        : %0d", cycle_cnt);
        $display("  Checks             : %0d passed, %0d failed", checks_pass, checks_fail);
        $display("=======================================================\n");

        if (fp16_mismatch == 0 && checks_fail == 0)
            $display(">>> SMOKE PASS: CPU + DMA + GEMM system plumbing OK <<<\n");
        else
            $display(">>> SMOKE FAIL (%0d mismatches, %0d check fails) <<<\n",
                     fp16_mismatch, checks_fail);

        $finish;
    end

    // =========================================================================
    // CPU elementwise kernels (stubs for the next milestone)
    //   - cpu_rmsnorm(row_base, n, eps)
    //   - cpu_rope(q_base, n_tokens, n_heads, head_dim)
    //   - cpu_silu_glu(x_base, gate_base, out_base, n)
    //   - cpu_residual_add(a_base, b_base, out_base, n_fp16)
    // They will operate on FP16 values packed in 72b TCDM words using
    // cpu_mem_read/cpu_mem_write, matching the log_quantizer semantics.
    // =========================================================================

endmodule
