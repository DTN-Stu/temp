    // -------------------------------------------------------------------------
    // DRAM MODEL (72b, indexed by TCDM 16-byte slot = addr>>4)
    // -------------------------------------------------------------------------
    logic [71:0] dram [0:TCDM_SLOTS-1];

    // -------------------------------------------------------------------------
    // Reference data
    // -------------------------------------------------------------------------
    logic [31:0] pre_addr [0:NUM_PRELOAD-1];
    logic [71:0] pre_data [0:NUM_PRELOAD-1];
    logic [71:0] exp_word [0:NUM_WORD-1];
    logic [71:0] out_words[0:NUM_WORD-1];

    int  checks_pass, checks_fail;
    int  fp16_match, fp16_mismatch;
    real max_abs_err;

    function automatic logic [31:0] tcdm_addr(input int word, input int bank);
        tcdm_addr = (32'(word) << 9) | (32'(bank) << 4);
    endfunction

    function automatic real fp16_to_real(input logic [15:0] hv);
        logic       s; logic [4:0] e; logic [9:0] mf; real v;
        s = hv[15]; e = hv[14:10]; mf = hv[9:0];
        if (e == 5'd0 && mf == 10'd0) return 0.0;
        if (e == 5'b11111) return s ? -999999.0 : 999999.0;
        if (e == 5'd0) v = real'(mf) / 16777216.0;
        else           v = (1.0 + real'(mf) / 1024.0) * $itor(32'd1 << e) / 32768.0;
        return s ? -v : v;
    endfunction

    // Round-to-nearest real -> IEEE FP16 (good enough for kernel self-tests).
    function automatic logic [15:0] real_to_fp16(input real v);
        logic        s; real a; int expn; logic [4:0] e; logic [9:0] mant;
        if (v == 0.0) return 16'h0000;
        s = (v < 0.0); a = s ? -v : v;
        expn = 0;
        while (a >= 2.0) begin a = a / 2.0; expn = expn + 1; end
        while (a <  1.0) begin a = a * 2.0; expn = expn - 1; end
        if (expn + 15 <= 0)  return {s, 5'd0, 10'd0};
        if (expn + 15 >= 31) return {s, 5'b11111, 10'd0};
        e = expn + 15;
        mant = $rtoi((a - 1.0) * 1024.0 + 0.5);
        if (mant >= 1024) begin mant = 10'd0; e = e + 5'd1; end
        return {s, e, mant};
    endfunction

    function automatic bit near(input real a, input real b, input real tol);
        real d;
        d = a - b; if (d < 0.0) d = -d;
        return (d <= tol);
    endfunction

    // --- FP4 log-scale quantizer helpers (mirror slq_encoder / log_quantizer) ---
    function automatic logic [7:0] mu_of(input logic [15:0] f);
        logic [4:0] E; logic [9:0] M;
        E = f[14:10]; M = f[9:0];
        if (E == 5'd0)  return 8'd0;
        if (E == 5'd31) return 8'd247;
        return {E, M[9:7]};
    endfunction

    function automatic logic [2:0] fp4_mag_of(input logic [7:0] d);
        if      (d <= 8'd2)  return 3'b111; // 6.0
        else if (d <= 8'd6)  return 3'b110; // 4.0
        else if (d <= 8'd10) return 3'b101; // 3.0
        else if (d <= 8'd14) return 3'b100; // 2.0
        else if (d <= 8'd18) return 3'b011; // 1.5
        else if (d <= 8'd24) return 3'b010; // 1.0
        else if (d <= 8'd36) return 3'b001; // 0.5
        else                 return 3'b000;
    endfunction

    task automatic check(input bit cond, input string name);
        if (cond) checks_pass = checks_pass + 1;
        else begin
            checks_fail = checks_fail + 1;
            $display("    [FAIL] %s", name);
        end
    endtask

    // =========================================================================
    // CPU MODEL  (CSR port + TCDM master 1)
    // =========================================================================
    task automatic cpu_csr_write(input logic [11:0] a, input logic [31:0] d);
        begin
            @(negedge clk);
            csr_req_valid = 1'b1; csr_req_write = 1'b1;
            csr_req_addr = a;     csr_req_data = d;
            #1;
            while (!csr_req_ready) begin @(negedge clk); #1; end
            @(posedge clk);
            @(negedge clk);
            csr_req_valid = 1'b0;
        end
    endtask

    task automatic cpu_csr_read(input logic [11:0] a, output logic [31:0] d);
        begin
            @(negedge clk);
            csr_req_valid = 1'b1; csr_req_write = 1'b0;
            csr_req_addr = a;     csr_req_data = 32'd0;
            #1;
            while (!csr_req_ready) begin @(negedge clk); #1; end
            @(posedge clk);
            @(negedge clk);
            csr_req_valid = 1'b0;
            d = csr_rsp_data;
        end
    endtask

    task automatic cpu_mem_write(input logic [31:0] a, input logic [71:0] d);
        begin
            @(negedge clk);
            cpu_mem_req_valid = 1'b1; cpu_mem_req_write = 1'b1;
            cpu_mem_req_addr = a; cpu_mem_req_wdata = d; cpu_mem_req_strb = 9'h1FF;
            #1;
            while (!cpu_mem_req_ready) begin @(negedge clk); #1; end
            @(posedge clk);
            @(negedge clk);
            cpu_mem_req_valid = 1'b0; cpu_mem_req_write = 1'b0; cpu_mem_req_strb = 9'h000;
        end
    endtask

    task automatic cpu_mem_read(input logic [31:0] a, output logic [71:0] d);
        begin
            @(negedge clk);
            cpu_mem_req_valid = 1'b1; cpu_mem_req_write = 1'b0;
            cpu_mem_req_addr = a; cpu_mem_req_wdata = '0; cpu_mem_req_strb = 9'h000;
            #1;
            while (!cpu_mem_req_ready) begin @(negedge clk); #1; end
            @(posedge clk);
            @(negedge clk);
            cpu_mem_req_valid = 1'b0;
            d = cpu_mem_rsp_rdata;
        end
    endtask

    // =========================================================================
    // DMA MODEL  (DRAM array + TCDM master 0)
    // =========================================================================
    task automatic dma_write(input logic [31:0] a, input logic [71:0] d);
        begin
            @(negedge clk);
            dma_mem_req_valid = 1'b1; dma_mem_req_write = 1'b1;
            dma_mem_req_addr = a; dma_mem_req_wdata = d; dma_mem_req_strb = 9'h1FF;
            #1;
            while (!dma_mem_req_ready) begin @(negedge clk); #1; end
            @(posedge clk);
            @(negedge clk);
            dma_mem_req_valid = 1'b0; dma_mem_req_write = 1'b0; dma_mem_req_strb = 9'h000;
        end
    endtask

    task automatic dma_read(input logic [31:0] a, output logic [71:0] d);
        begin
            @(negedge clk);
            dma_mem_req_valid = 1'b1; dma_mem_req_write = 1'b0;
            dma_mem_req_addr = a; dma_mem_req_wdata = '0; dma_mem_req_strb = 9'h000;
            #1;
            while (!dma_mem_req_ready) begin @(negedge clk); #1; end
            @(posedge clk);
            @(negedge clk);
            dma_mem_req_valid = 1'b0;
            d = dma_mem_rsp_rdata;
        end
    endtask

    // Descriptor-style block copy: 16-byte slots, dir 0 = DRAM->TCDM, 1 = reverse.
    // This is exactly the operation a dma_desc (dram_addr, tcdm_addr, size, dir)
    // asks the external DMA to perform.
    task automatic dma_block_copy(input logic [31:0] dram_byte,
                                  input logic [31:0] tcdm_byte,
                                  input int unsigned nslots,
                                  input logic dir);
        int unsigned i;
        logic [71:0] w;
        begin
            for (i = 0; i < nslots; i++) begin
                if (dir == 1'b0) begin
                    dma_write(tcdm_byte + (i << 4), dram[(dram_byte >> 4) + i]);
                end else begin
                    dma_read(tcdm_byte + (i << 4), w);
                    dram[(dram_byte >> 4) + i] = w;
                end
            end
        end
    endtask

    // =========================================================================
    // CPU ELEMENTWISE KERNELS  (operate on 4 FP16 packed in one 72b TCDM word)
    //   These are the "remaining" ops of a LLaMA layer that have no HW block.
    // =========================================================================
    task automatic cpu_rmsnorm4(input logic [31:0] a,
                                input real g0, g1, g2, g3);
        logic [71:0] w; real x0,x1,x2,x3, inv;
        begin
            cpu_mem_read(a, w);
            x0 = fp16_to_real(w[15:0]);  x1 = fp16_to_real(w[31:16]);
            x2 = fp16_to_real(w[47:32]); x3 = fp16_to_real(w[63:48]);
            inv = 1.0 / $sqrt((x0*x0 + x1*x1 + x2*x2 + x3*x3) / 4.0);
            w = 72'd0;
            w[15:0]  = real_to_fp16(x0*inv*g0); w[31:16] = real_to_fp16(x1*inv*g1);
            w[47:32] = real_to_fp16(x2*inv*g2); w[63:48] = real_to_fp16(x3*inv*g3);
            cpu_mem_write(a, w);
        end
    endtask

    task automatic cpu_silu4(input logic [31:0] a);
        logic [71:0] w; real x0,x1,x2,x3;
        begin
            cpu_mem_read(a, w);
            x0 = fp16_to_real(w[15:0]);  x1 = fp16_to_real(w[31:16]);
            x2 = fp16_to_real(w[47:32]); x3 = fp16_to_real(w[63:48]);
            w = 72'd0;
            w[15:0]  = real_to_fp16(x0/(1.0+$exp(-x0)));
            w[31:16] = real_to_fp16(x1/(1.0+$exp(-x1)));
            w[47:32] = real_to_fp16(x2/(1.0+$exp(-x2)));
            w[63:48] = real_to_fp16(x3/(1.0+$exp(-x3)));
            cpu_mem_write(a, w);
        end
    endtask

    task automatic cpu_residual4(input logic [31:0] a, input logic [31:0] b);
        logic [71:0] wa, wb, wo;
        begin
            cpu_mem_read(a, wa);
            cpu_mem_read(b, wb);
            wo = 72'd0;
            wo[15:0]  = real_to_fp16(fp16_to_real(wa[15:0])  + fp16_to_real(wb[15:0]));
            wo[31:16] = real_to_fp16(fp16_to_real(wa[31:16]) + fp16_to_real(wb[31:16]));
            wo[47:32] = real_to_fp16(fp16_to_real(wa[47:32]) + fp16_to_real(wb[47:32]));
            wo[63:48] = real_to_fp16(fp16_to_real(wa[63:48]) + fp16_to_real(wb[63:48]));
            cpu_mem_write(a, wo);
        end
    endtask

    // CPU FP4 quantizer: read 16 FP16 (4 words: src_word..src_word+3, same bank),
    // emit one 72b packet {scale[7:0], 16 x 4b code} at dst.  Mirrors the RTL
    // log_quantizer (slq_encoder.sv): block max on mu, log8 S4.3 scale, E2M1 codes.
    task automatic cpu_quantize16(input int src_word, input int src_bank,
                                  input int dst_word, input int dst_bank);
        logic [71:0] wds [0:3];
        logic [15:0] f;
        logic [7:0]  mu [0:15];
        logic [7:0]  mx, dmn, dd;
        integer      sc, k, i;
        logic [3:0]  code;
        logic [2:0]  mag;
        logic [71:0] pkt;
        begin
            for (k = 0; k < 4; k++)
                cpu_mem_read(tcdm_addr(src_word + k, src_bank), wds[k]);
            mx = 8'd0;
            for (i = 0; i < 16; i++) begin
                f = wds[i/4][(i % 4)*16 +: 16];
                mu[i] = mu_of(f);
                if (mu[i] > mx) mx = mu[i];
            end
            if (mx == 8'd0) sc = 0;
            else begin
                sc = int'(mx) - 140;
                if (sc > 127) sc = 127;
                if (sc < -128) sc = -128;
            end
            pkt = 72'd0;
            for (i = 0; i < 16; i++) begin
                f  = wds[i/4][(i % 4)*16 +: 16];
                dd = mx - mu[i];
                if (mu[i] == 8'd0 || mx == 8'd0) mag = 3'b000;
                else                              mag = fp4_mag_of(dd);
                code = (mag == 3'b000) ? 4'b0000 : {f[15], mag};
                pkt[4*i +: 4] = code;
            end
            pkt[71:64] = sc[7:0];
            cpu_mem_write(tcdm_addr(dst_word, dst_bank), pkt);
        end
    endtask

    // =========================================================================
    // Main sequence
    // =========================================================================
    int i, cycle_cnt;
    logic [31:0] rd32;
    logic [71:0] peek;
    bit seen_done, seen_busy;
    localparam logic [71:0] POKE_VAL = 72'hCAFE_0000_0000_0000_5A;
    localparam logic [31:0] POKE_ADDR = 32'h0003_E940; // bank20, word500 (unused)
    // Scratch words for CPU elementwise kernel self-tests (bank21, words 600..603)
    localparam logic [31:0] K_RMS   = 32'h0004_B150;
    localparam logic [31:0] K_SILU  = 32'h0004_B350;
    localparam logic [31:0] K_RES_A = 32'h0004_B550;
    localparam logic [31:0] K_RES_B = 32'h0004_B750;
    logic [71:0] kw, rw;

    initial begin
        csr_req_valid = 1'b0; csr_req_write = 1'b0; csr_req_addr = '0; csr_req_data = '0;
        csr_rsp_ready = 1'b1;
        cpu_mem_req_valid = 1'b0; cpu_mem_req_write = 1'b0; cpu_mem_req_addr = '0;
        cpu_mem_req_wdata = '0; cpu_mem_req_strb = '0;
        dma_mem_req_valid = 1'b0; dma_mem_req_write = 1'b0; dma_mem_req_addr = '0;
        dma_mem_req_wdata = '0; dma_mem_req_strb = '0;
        dma_desc_ready = 1'b1; dma_desc_done = 1'b0;

        checks_pass = 0; checks_fail = 0;
        fp16_match = 0; fp16_mismatch = 0; max_abs_err = 0.0;

        $readmemh("sim_snax_llm_top_gemm/hex/tcdm_preload_addr.hex", pre_addr);
        $readmemh("sim_snax_llm_top_gemm/hex/tcdm_preload_data.hex", pre_data);
        $readmemh("sim_snax_llm_top_gemm/hex/expected_out_words.hex", exp_word);

        wait (rst_n == 1'b1);
        repeat (10) @(posedge clk);

        $display("\n=======================================================");
        $display("  tb_snax_llm_layer_smoke: CPU + DMA + GEMM system smoke");
        $display("  M=%0d N=%0d K=%0d  (M_T=%0d N_T=%0d K_B=%0d)",
                 M_TILES*16, N_TILES*16, K_BLOCKS*16, M_TILES, N_TILES, K_BLOCKS);
        $display("=======================================================");

        // 1. Build DRAM image from the preload list (slot = tcdm_addr>>4)
        $display("[1] Building DRAM image (%0d slots) from preload list ...", TCDM_SLOTS);
        for (i = 0; i < TCDM_SLOTS; i++) dram[i] = 72'd0;
        for (i = 0; i < NUM_PRELOAD; i++) dram[pre_addr[i] >> 4] = pre_data[i];

        // 2. DMA block-copy DRAM -> TCDM (descriptor semantics)
        $display("[2] DMA block-copy DRAM -> TCDM (%0d slots = %0d bytes) ...",
                 TCDM_SLOTS, TCDM_BYTES);
        dma_block_copy(32'd0, 32'd0, TCDM_SLOTS, 1'b0);

        // 3. CPU master-1 sanity: poke/peek a scratch word
        $display("[3] CPU TCDM poke/peek @0x%08X ...", POKE_ADDR);
        cpu_mem_write(POKE_ADDR, POKE_VAL);
        cpu_mem_read(POKE_ADDR, peek);
        check(peek === POKE_VAL, "CPU TCDM read/write (master 1)");

        // 3b. CPU elementwise kernels (the LLaMA ops with no HW block)
        $display("[3b] CPU elementwise kernel self-tests (RMSNorm/SiLU/residual) ...");
        // RMSNorm: x=[1,2,3,4], gamma=1 -> [0.3651,0.7303,1.0954,1.4606]
        kw = 72'd0;
        kw[15:0] = real_to_fp16(1.0); kw[31:16] = real_to_fp16(2.0);
        kw[47:32]= real_to_fp16(3.0); kw[63:48] = real_to_fp16(4.0);
        cpu_mem_write(K_RMS, kw);
        cpu_rmsnorm4(K_RMS, 1.0, 1.0, 1.0, 1.0);
        cpu_mem_read(K_RMS, rw);
        check(near(fp16_to_real(rw[15:0]),  0.3651, 0.01), "RMSNorm lane0");
        check(near(fp16_to_real(rw[31:16]), 0.7303, 0.01), "RMSNorm lane1");
        check(near(fp16_to_real(rw[47:32]), 1.0954, 0.01), "RMSNorm lane2");
        check(near(fp16_to_real(rw[63:48]), 1.4606, 0.01), "RMSNorm lane3");
        // SiLU: x=[-2,-1,1,2] -> [-0.2384,-0.2689,0.7311,1.7616]
        kw = 72'd0;
        kw[15:0] = real_to_fp16(-2.0); kw[31:16] = real_to_fp16(-1.0);
        kw[47:32]= real_to_fp16(1.0);  kw[63:48] = real_to_fp16(2.0);
        cpu_mem_write(K_SILU, kw);
        cpu_silu4(K_SILU);
        cpu_mem_read(K_SILU, rw);
        check(near(fp16_to_real(rw[15:0]),  -0.2384, 0.02), "SiLU lane0");
        check(near(fp16_to_real(rw[31:16]), -0.2689, 0.02), "SiLU lane1");
        check(near(fp16_to_real(rw[47:32]),  0.7311, 0.02), "SiLU lane2");
        check(near(fp16_to_real(rw[63:48]),  1.7616, 0.02), "SiLU lane3");
        // Residual: [1,2,3,4] + [0.5,0.5,0.5,0.5] -> [1.5,2.5,3.5,4.5]
        kw = 72'd0;
        kw[15:0]=real_to_fp16(1.0); kw[31:16]=real_to_fp16(2.0);
        kw[47:32]=real_to_fp16(3.0); kw[63:48]=real_to_fp16(4.0);
        cpu_mem_write(K_RES_A, kw);
        kw = 72'd0;
        kw[15:0]=real_to_fp16(0.5); kw[31:16]=real_to_fp16(0.5);
        kw[47:32]=real_to_fp16(0.5); kw[63:48]=real_to_fp16(0.5);
        cpu_mem_write(K_RES_B, kw);
        cpu_residual4(K_RES_A, K_RES_B);
        cpu_mem_read(K_RES_A, rw);
        check(near(fp16_to_real(rw[15:0]),  1.5, 0.01), "residual lane0");
        check(near(fp16_to_real(rw[31:16]), 2.5, 0.01), "residual lane1");
        check(near(fp16_to_real(rw[47:32]), 3.5, 0.01), "residual lane2");
        check(near(fp16_to_real(rw[63:48]), 4.5, 0.01), "residual lane3");

        // 3c. CPU FP4 quantizer: FP16 block -> 72b packet (bit-exact vs RTL model)
        $display("[3c] CPU FP4 quantizer (FP16 block -> packet) ...");
        kw = 72'd0; kw[15:0]=real_to_fp16(1.0);  kw[31:16]=real_to_fp16(-1.0);
        kw[47:32]=real_to_fp16(2.0);  kw[63:48]=real_to_fp16(-2.0);
        cpu_mem_write(tcdm_addr(700,22), kw);
        kw = 72'd0; kw[15:0]=real_to_fp16(3.0);  kw[31:16]=real_to_fp16(-3.0);
        kw[47:32]=real_to_fp16(0.5);  kw[63:48]=real_to_fp16(-0.5);
        cpu_mem_write(tcdm_addr(701,22), kw);
        kw = 72'd0; kw[15:0]=real_to_fp16(4.0);  kw[31:16]=real_to_fp16(-4.0);
        kw[47:32]=real_to_fp16(6.0);  kw[63:48]=real_to_fp16(-6.0);
        cpu_mem_write(tcdm_addr(702,22), kw);
        kw = 72'd0; kw[15:0]=real_to_fp16(0.25); kw[31:16]=real_to_fp16(-0.25);
        kw[47:32]=real_to_fp16(1.5);  kw[63:48]=real_to_fp16(-1.5);
        cpu_mem_write(tcdm_addr(703,22), kw);
        cpu_quantize16(700, 22, 704, 22);
        cpu_mem_read(tcdm_addr(704,22), rw);
        check(rw === 72'h00B391F7E691D5C4A2, "CPU FP4 quantizer (packet bit-exact)");

        // 3d. HW readback-requant job: exercises the REAL RTL log_quantizer.
        //     read streamer (master20) reads FP16 -> log_quantizer -> write-out
        //     FP4 (master19) writes the 72b packet.  Compare to the CPU golden.
        $display("[3d] HW readback-requant job (RTL log_quantizer) ...");
        kw = 72'd0; kw[15:0]=real_to_fp16(1.0);  kw[31:16]=real_to_fp16(-1.0);
        kw[47:32]=real_to_fp16(2.0);  kw[63:48]=real_to_fp16(-2.0);
        cpu_mem_write(tcdm_addr(800,23), kw);
        kw = 72'd0; kw[15:0]=real_to_fp16(3.0);  kw[31:16]=real_to_fp16(-3.0);
        kw[47:32]=real_to_fp16(0.5);  kw[63:48]=real_to_fp16(-0.5);
        cpu_mem_write(tcdm_addr(801,23), kw);
        kw = 72'd0; kw[15:0]=real_to_fp16(4.0);  kw[31:16]=real_to_fp16(-4.0);
        kw[47:32]=real_to_fp16(6.0);  kw[63:48]=real_to_fp16(-6.0);
        cpu_mem_write(tcdm_addr(802,23), kw);
        kw = 72'd0; kw[15:0]=real_to_fp16(0.25); kw[31:16]=real_to_fp16(-0.25);
        kw[47:32]=real_to_fp16(1.5);  kw[63:48]=real_to_fp16(-1.5);
        cpu_mem_write(tcdm_addr(803,23), kw);

        cpu_csr_write(A_CTRL,    32'h0);
        cpu_csr_write(A_SEQ_CTRL,32'h3);                  // op_mode=11 (readback), no DMA
        cpu_csr_write(A_RD_BASE, tcdm_addr(800,23));      // FP16 source (4 words)
        cpu_csr_write(A_RD_NV,   32'd1);                  // 1 vector = 16 FP16
        cpu_csr_write(A_RD_LS,   32'h200);                // word stride
        cpu_csr_write(A_WO_BASE, tcdm_addr(810,23));      // packet destination
        cpu_csr_write(A_START,   32'h0000_0003);

        seen_done = 1'b0; seen_busy = 1'b0; cycle_cnt = 0;
        while (!seen_done && cycle_cnt < 20000) begin
            @(posedge clk);
            cycle_cnt = cycle_cnt + 1;
            if (busy) seen_busy = 1'b1;
            if (seen_busy && done_irq && !busy) seen_done = 1'b1;
        end
        check(seen_done, "readback-requant job finished");
        cpu_mem_read(tcdm_addr(810,23), rw);
        check(rw === 72'h00B391F7E691D5C4A2, "HW log_quantizer packet bit-exact");

        // 4. CPU programs the sequencer descriptor and launches GEMM
        $display("[4] CPU programs CSR and launches GEMM ...");
        cpu_csr_read(A_RO_ID, rd32);
        check(rd32 == CSR_ID_VALUE, "CSR hardware ID (SNAF)");

        cpu_csr_write(A_CTRL,      32'h0);        // sequencer owns control
        cpu_csr_write(A_SEQ_CTRL,  32'h0);        // op_mode=00 GEMM, DMA off
        cpu_csr_write(A_GEMM_NT,   N_TILES);
        cpu_csr_write(A_GEMM_MT,   M_TILES);
        cpu_csr_write(A_GEMM_KB,   K_BLOCKS);
        cpu_csr_write(A_RING_BASE, RING_BASE);
        cpu_csr_write(A_Q_BASE,    Q_BASE);
        cpu_csr_write(A_OUT_BASE,  OUT_BASE);
        cpu_csr_write(A_WO_BASE,   OUT_BASE);
        cpu_csr_write(A_WO_NV,     NUM_VEC);
        cpu_csr_write(A_WO_LS,     32'h200);
        cpu_csr_write(A_START,     32'h0000_0003);

        // 5. Wait for completion
        seen_done = 1'b0; seen_busy = 1'b0; cycle_cnt = 0;
        while (!seen_done && cycle_cnt < 20000) begin
            @(posedge clk);
            cycle_cnt = cycle_cnt + 1;
            if (busy) seen_busy = 1'b1;
            if (seen_busy && done_irq && !busy) seen_done = 1'b1;
        end
        $display("    Completed in %0d cycles (busy=%0b done_irq=%0b)",
                 cycle_cnt, busy, done_irq);
        check(seen_done, "Sequencer finished without timeout");

        repeat (50) @(posedge clk);

        // 6. DMA reads back result words from bank 17, compare bit-exact
        $display("[6] DMA readback %0d words from bank %0d, checking ...",
                 NUM_WORD, OUT_BANK);
        for (i = 0; i < NUM_WORD; i++) dma_read(tcdm_addr(i, OUT_BANK), out_words[i]);

        for (i = 0; i < NUM_WORD; i++) begin
            for (int e = 0; e < 4; e++) begin
                logic [15:0] afp, efp;
                real ar, er, diff;
                afp = out_words[i][e*16 +: 16];
                efp = exp_word[i][e*16 +: 16];
                ar = fp16_to_real(afp); er = fp16_to_real(efp);
                diff = ar - er; if (diff < 0.0) diff = -diff;
                if (diff > max_abs_err) max_abs_err = diff;
                if (afp === efp) fp16_match = fp16_match + 1;
                else begin
                    fp16_mismatch = fp16_mismatch + 1;
                    if (fp16_mismatch <= 10)
                        $display("    Mismatch word=%0d elem=%0d: act=0x%04X exp=0x%04X",
                                 i, e, afp, efp);
                end
            end
        end

        $display("\n=======================================================");
        $display("  SYSTEM SMOKE RESULTS");
        $display("=======================================================");
        $display("  FP16 Matches       : %0d / %0d", fp16_match, NUM_FP16);
        $display("  FP16 Mismatches    : %0d", fp16_mismatch);
        $display("  Max Absolute Error : %f", max_abs_err);
        $display("  GEMM Cycles        : %0d", cycle_cnt);
        $display("  Checks             : %0d passed, %0d failed", checks_pass, checks_fail);
        $display("=======================================================\n");

        if (fp16_mismatch == 0 && checks_fail == 0)
            $display(">>> SMOKE PASS: CPU + DMA + GEMM system plumbing OK <<<\n");
        else
            $display(">>> SMOKE FAIL (%0d mismatches, %0d check fails) <<<\n",
                     fp16_mismatch, checks_fail);

        $finish;
    end

